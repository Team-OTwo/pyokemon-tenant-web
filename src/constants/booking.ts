// ERD 데이터를 프론트엔드 표시용으로 변환하는 함수
export const convertBookingToDisplay = (booking: Booking): BookingDisplay => {
  const paymentStatusMap = {
    PENDING: "결제대기" as const,
    COMPLETED: "결제완료" as const,
    CANCELLED: "결제취소" as const,
    FAILED: "결제취소" as const,
  }

  return {
    id: booking.id.toString(),
    purchaser: booking.user?.name || "알 수 없음",
    bookingPid: booking.booking_id,
    seat: booking.seat_class?.seat_class_name || "알 수 없음",
    amount: booking.payment?.total_price || 0,
    paymentMethod: booking.payment?.method || "알 수 없음",
    paymentStatus: paymentStatusMap[booking.payment?.status || "PENDING"],
    eventId: booking.event?.eventId || "",
    eventTitle: booking.event?.title || "",
    eventDate: booking.event_schedule?.event_date || "",
    venueName: booking.venue?.venue_name || "",
    thumbnailUrl: "/mock/thumbnail1.jpg",
  }
}

